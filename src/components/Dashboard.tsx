// ─── Types ─────────────────────────────────────────────────────────────────

interface IngredientRow {
  name: string;
  risk: 'safe' | 'caution' | 'hazard';
  role: string;
  confidence: string;
}

interface AnalysisResult {
  productName: string;
  safetyScore: number;
  riskLabel: string;
  ingredientCount: number;
  researchConfidence: number;
  summary: string;
  warnings: string[];
  ingredients: IngredientRow[];
  report: string;
  sampleMode: boolean;
}

interface ResearchResult {
  purpose?: string;
  human_safety_status?: string;
  evidence_based_safety_assessment?: string;
  confidence_score?: string;
}

interface ApiResponse {
  success: boolean;
  product_name: string;
  safety_score: number | null;
  risk_label: string | null;
  ocr_text: string;
  ingredients: string[];
  research_results: Record<string, ResearchResult>;
  safety_analysis: {
    summary?: string;
    warnings?: string[];
    recommendations?: string[];
    overall_score?: string | number;
  };
  markdown_report: string;
  json_report: Record<string, unknown>;
  report_md_path: string;
  report_json_path: string;
  source_image_path?: string;
  sample_image_used?: boolean;
}

interface BackendHealth {
  loading: boolean;
  reachable: boolean;
  status?: 'ok' | 'degraded';
  gemini?: boolean;
  tavily?: boolean;
  message?: string;
  lastChecked?: number;
  port?: number;
  host?: string;
}

