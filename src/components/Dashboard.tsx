type PipelineStep = 0 | 1 | 2 | 3 | 4 | 5 | 6;

// ─── Backend response → UI mapping ─────────────────────────────────────────

const riskFromStatus = (status: string): IngredientRow['risk'] => {
  const s = (status ?? '').toLowerCase();
  if (/(not recommended|danger|high risk)/.test(s)) return 'hazard';
  if (/(caution|conditions|insufficient|medium)/.test(s)) return 'caution';
  return 'safe';
};

const mapResult = (data: ApiResponse): AnalysisResult => {
  const safety = data.safety_analysis ?? {};
  const research = data.research_results ?? {};

  const ingredients: IngredientRow[] = (data.ingredients ?? []).map((name: string) => {
    const rep = research[name] ?? {};
    return {
      name,
      role: rep.purpose || '—',
      risk: riskFromStatus(rep.human_safety_status ?? rep.evidence_based_safety_assessment ?? ''),
      confidence: rep.confidence_score || 'Unknown',
    };
  });

  const confValues: Record<string, number> = { High: 100, Medium: 70, Low: 40 };
  const confs = ingredients.map((i) => confValues[i.confidence] ?? 0);
  const researchConfidence = confs.length
    ? Math.round(confs.reduce((a, b) => a + b, 0) / confs.length)
    : 0;

  const hasIngredients = ingredients.length > 0;

  // Prefer numeric safety_score from pipeline (report node). Fallback to
  // safety_analysis.overall_score if that's what the LLM returned.
  let score: number;
  if (typeof data.safety_score === 'number') {
    score = data.safety_score;
  } else if (typeof safety.overall_score === 'number') {
    score = safety.overall_score;
  } else if (typeof safety.overall_score === 'string') {
    const m = /\b(100|[1-9]?\d)\b/.exec(safety.overall_score);
    score = m ? Number(m[1]) : 0;
  } else {
    score = 0;
  }

  let riskLabel: string;
  if (hasIngredients) {
    riskLabel =
      data.risk_label ||
      (score >= 80 ? 'Safe / Low Risk' : score >= 50 ? 'Caution / Medium Risk' : 'Danger / High Risk');
  } else {
    riskLabel = 'No Ingredients Detected';
  }

  const summary = hasIngredients
    ? safety.summary || 'No summary available.'
    : 'No ingredients were detected in this image. Try a clearer, higher-resolution product label.';

  return {
    productName: data.product_name || 'Analyzed Product',
    safetyScore: score,
    riskLabel,
    ingredientCount: ingredients.length,
    researchConfidence,
    summary,
    warnings: hasIngredients ? safety.warnings || [] : [],
    ingredients,
    report: data.markdown_report || 'No report was generated by the pipeline.',
    sampleMode: !!data.sample_image_used,
  };
};

// ─── Backend Configuration ────────────────────────────────────────────────

// Use environment variable if set (for production deployments)
// Otherwise fallback to relative path (/api) which works when frontend/backend are on same domain
// Note: __BACKEND_URL__ is replaced at build time by Vite's define option
const getApiUrl = (endpoint: string) => {
  // @ts-ignore - __BACKEND_URL__ is defined in vite.config.ts at build time
  const backendUrl = __BACKEND_URL__ || '';
  
  // If we have a full URL (production), use it
  if (backendUrl && !backendUrl.startsWith('http')) {
    // It's a relative path, append endpoint
    return `${backendUrl}${endpoint}`;
  }
  // If it's a full URL, ensure we don't double-slash join
  return backendUrl ? `${backendUrl.replace(/\/$/, '')}${endpoint}` : endpoint;
};

